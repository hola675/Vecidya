import test from "node:test";
import assert from "node:assert/strict";
import {
  BANK, QUESTION_BY_ID, activeOf, capabilityProvenance, mulberry32, pick, runChain, runPolicyRoute, solutionIds, structuralViolations, without,
  type AnswerPolicy,
} from "./qbv2-candidate-qa-harness";
import { CANDIDATE_ROUTE_HARD_CAP_V3, type CandidateQuestionPlanV3 } from "../../../app/features/diagnostic/qbv2-candidate-planner";
import type { QuestionDefinitionV2 } from "../../../app/features/diagnostic/qbv2-contract";
import type { AnswersV2 } from "../../../app/features/diagnostic/qbv2-rules";

/**
 * DIAG-V3-R7-B deterministic fuzz/property campaign. Fuzz inputs are NOT human-authored truth scenarios
 * (unlike R7-A canonical cases): they are generated by a seeded, reproducible answer policy over valid
 * candidate option values only, to find STRUCTURAL violations. Nothing here asserts that a score, band or
 * license is business-correct, and nothing reads network, time or `Math.random`.
 */

export const FUZZ_SEED = 20261007;
const ROUTED_RUNS = 540;
const INTERPRETED_RUNS = 450;
const FAMILIES = ["prelaunch", "professional", "appointments", "retail", "ecommerce", "b2b", "creator", "organization", "hybrid"] as const;
type Family = (typeof FAMILIES)[number];
const STRUCTURAL = ["q2_delivery", "q2_has_customers", "q2_customer_buyer", "q2_entity", "q2_monetization", "q2_sector", "q2_goal"];

function structuralValue(family: Family, question: QuestionDefinitionV2, rng: () => number): string | readonly string[] | undefined {
  switch (question.id) {
    case "q2_has_customers": return family === "prelaunch" ? "no" : "yes";
    case "q2_entity": return family === "organization" ? "organization" : family === "prelaunch" ? pick(rng, ["project", "individual", "business"]) : pick(rng, ["individual", "business"]);
    case "q2_monetization": return family === "organization" ? "mission" : family === "creator" ? "audience" : ["retail", "ecommerce"].includes(family) ? "goods" : undefined;
    case "q2_customer_buyer": return family === "b2b" ? pick(rng, ["b2b", "mixed"]) : undefined;
    case "q2_sector": return family === "professional" ? pick(rng, ["legal", "financial_tax_insurance", "professional_services", "real_estate"]) : family === "retail" ? "retail" : undefined;
    case "q2_delivery": {
      const byFamily: Partial<Record<Family, readonly (readonly string[])[]>> = {
        professional: [["other"], ["appointments"], ["travels"]], appointments: [["appointments"]], retail: [["retail"], ["physical_location", "retail"]],
        ecommerce: [["online_checkout"]], b2b: [["other"], ["onsite"]], creator: [["online_checkout"], ["other"]], organization: [["other"], ["physical_location"]],
      };
      if (family === "hybrid") {
        const pool = ["retail", "online_checkout", "appointments", "travels", "physical_location"];
        const first = pick(rng, pool);
        return [first, pick(rng, pool.filter((v) => v !== first))];
      }
      return byFamily[family] ? pick(rng, byFamily[family]!) : undefined;
    }
    default: return undefined;
  }
}

/** Controlled class probabilities: unknown 12%, N/A 8% (where the option exists), otherwise any substantive option. */
function randomValue(question: QuestionDefinitionV2, rng: () => number): string | readonly string[] {
  const unknown = question.options.find((o) => o.kind === "unknown");
  const na = question.options.find((o) => o.kind === "not_applicable");
  const substantive = question.options.filter((o) => o.kind === undefined || o.kind === "value");
  const roll = rng();
  if (unknown && roll < 0.12) return question.type === "multi" ? [unknown.value] : unknown.value;
  if (na && roll < 0.2) return na.value;
  if (question.type === "multi") {
    const nonExclusive = substantive.filter((o) => !o.exclusive);
    const exclusive = substantive.filter((o) => o.exclusive);
    if (exclusive.length > 0 && (nonExclusive.length === 0 || rng() < 0.3)) return [pick(rng, exclusive).value];
    const first = pick(rng, nonExclusive).value;
    const rest = nonExclusive.filter((o) => o.value !== first);
    return rest.length > 0 && rng() < 0.4 ? [first, pick(rng, rest).value] : [first];
  }
  return pick(rng, substantive).value;
}

function policyFor(family: Family, rng: () => number): AnswerPolicy {
  return (question) => structuralValue(family, question, rng) ?? randomValue(question, rng);
}

/** Independent, reproducible generator per route: any single run can be replayed in isolation. */
const runSeed = (index: number) => (FUZZ_SEED + Math.imul(index + 1, 0x9e3779b1)) >>> 0;
type RoutedRun = { index: number; family: Family; asked: string[]; finalAnswers: AnswersV2; terminalReason: string; hardCap: boolean; plan: CandidateQuestionPlanV3 };
let routed: RoutedRun[] | undefined;
const timings: Record<string, number> = {};
function routedRuns(): RoutedRun[] {
  if (routed) return routed;
  const started = performance.now();
  routed = Array.from({ length: ROUTED_RUNS }, (_, index) => {
    const family = FAMILIES[index % FAMILIES.length]!;
    const route = runPolicyRoute(policyFor(family, mulberry32(runSeed(index))));
    return { index, family, asked: route.asked, finalAnswers: route.finalAnswers, terminalReason: route.plan.completion.terminalReason, hardCap: route.plan.completion.hardCapReached, plan: route.plan };
  });
  timings.routedMs = Math.round(performance.now() - started);
  return routed;
}

test("Fuzz: seeded routed campaign — every route terminates with zero structural violations", () => {
  const violations: string[] = [];
  for (const run of routedRuns()) {
    const result = runChain(run.finalAnswers);
    for (const v of structuralViolations(result, { route: { asked: run.asked, plan: run.plan } })) violations.push(`#${run.index}/${run.family}: ${v}`);
    if (run.asked.length > CANDIDATE_ROUTE_HARD_CAP_V3) violations.push(`#${run.index}: hard cap exceeded`);
    for (const id of run.asked) {
      const value = run.finalAnswers[id];
      if (value === undefined) continue; // answered then legitimately invalidated by a later structural answer
      const q = QUESTION_BY_ID.get(id)!;
      for (const item of Array.isArray(value) ? value : [value]) if (!q.options.some((o) => o.value === item)) violations.push(`#${run.index}: invalid answer ${id}=${item}`);
    }
  }
  assert.deepEqual(violations, [], violations.slice(0, 20).join("\n"));
});

test("Fuzz: determinism — repeated routes and repeated chains are identical (deterministic subset)", () => {
  const runs = routedRuns();
  for (const run of runs.filter((r) => r.index % 18 === 0)) {
    const replay = runPolicyRoute(policyFor(run.family, mulberry32(runSeed(run.index))));
    assert.deepEqual(replay.asked, run.asked, `#${run.index}: route not reproducible`);
    assert.deepEqual(replay.finalAnswers, run.finalAnswers, `#${run.index}: final answers not reproducible`);
    assert.deepEqual(runChain(run.finalAnswers), runChain(run.finalAnswers), `#${run.index}: chain not deterministic`);
  }
});

test("Fuzz: invalidation subset — mutating one structural answer filters every stale answer and its provenance", () => {
  const rng = mulberry32(FUZZ_SEED ^ 0x5a5a);
  let mutated = 0;
  let staleTotal = 0;
  for (const run of routedRuns().filter((r) => r.index % 10 === 0)) {
    const candidates = STRUCTURAL.filter((id) => run.finalAnswers[id] !== undefined);
    if (candidates.length === 0) continue;
    const id = pick(rng, candidates);
    const q = QUESTION_BY_ID.get(id)!;
    const current = JSON.stringify(run.finalAnswers[id]);
    const alternatives = q.options.filter((o) => JSON.stringify(q.type === "multi" ? [o.value] : o.value) !== current);
    const value = pick(rng, alternatives).value;
    const raw = { ...run.finalAnswers, [id]: q.type === "multi" ? [value] : value };
    const result = runChain(raw);
    const stale = Object.keys(run.finalAnswers).filter((key) => key !== id && result.activeAnswers[key] === undefined);
    staleTotal += stale.length;
    mutated += 1;
    const provenance = capabilityProvenance(result);
    for (const key of stale) assert.equal(provenance.has(key), false, `#${run.index} ${id}=${value}: stale ${key} survived as provenance`);
    assert.deepEqual(result, runChain(without(raw, ...stale)), `#${run.index} ${id}=${value}: stale raw answers changed the result`);
    assert.deepEqual(structuralViolations(result), [], `#${run.index} ${id}=${value}`);
  }
  timings.invalidationMutations = mutated;
  timings.invalidationStaleAnswers = staleTotal;
  assert.ok(mutated >= 40 && staleTotal > 0);
});

test("Fuzz: interpreted campaign — random raw answer sets (with inactive pollution) never violate structure, and inactive raw keys never matter", () => {
  const started = performance.now();
  const rng = mulberry32(FUZZ_SEED + 1);
  const violations: string[] = [];
  for (let index = 0; index < INTERPRETED_RUNS; index += 1) {
    const family = FAMILIES[index % FAMILIES.length]!;
    const raw: Record<string, string | readonly string[]> = {};
    for (const q of BANK) {
      const forced = structuralValue(family, q, rng);
      if (forced !== undefined) raw[q.id] = forced;
      else if (rng() < 0.7) raw[q.id] = randomValue(q, rng);
    }
    const result = runChain(raw as AnswersV2);
    for (const v of structuralViolations(result)) violations.push(`i#${index}/${family}: ${v}`);
    if (index % 3 === 0) {
      try { assert.deepStrictEqual(runChain(activeOf(raw as AnswersV2)), result); } catch { violations.push(`i#${index}/${family}: inactive raw answers changed the result`); }
    }
  }
  timings.interpretedMs = Math.round(performance.now() - started);
  assert.deepEqual(violations, [], violations.slice(0, 20).join("\n"));
});

test("Fuzz outcome statistics (OBSERVATIONAL — QA record only, never calibration input)", () => {
  const runs = routedRuns();
  const lengths = runs.map((r) => r.asked.length).sort((a, b) => a - b);
  const terminal: Record<string, number> = {};
  const license: Record<string, number> = {};
  const families: Record<string, number> = {};
  const applicable: Record<string, number> = {};
  const nullScore: Record<string, number> = {};
  let answers = 0, unknown = 0, na = 0, recommendations = 0, nullSolutions = 0, supportingOnlySolutions = 0, automationOnInformal = 0;
  for (const run of runs) {
    terminal[run.terminalReason] = (terminal[run.terminalReason] ?? 0) + 1;
    families[run.family] = (families[run.family] ?? 0) + 1;
    for (const id of run.asked) {
      const value = run.finalAnswers[id];
      if (value === undefined) continue;
      answers += 1;
      const kinds = (Array.isArray(value) ? value : [value]).map((v) => QUESTION_BY_ID.get(id)!.options.find((o) => o.value === v)?.kind);
      if (kinds.includes("unknown")) unknown += 1;
      if (kinds.includes("not_applicable")) na += 1;
    }
    const result = runChain(run.finalAnswers);
    const key = result.commercial.licenseFit.recommendedLicense ?? "null";
    license[key] = (license[key] ?? 0) + 1;
    for (const d of result.scoring.dimensions) {
      if (d.applicability === "applicable") applicable[d.id] = (applicable[d.id] ?? 0) + 1;
      if (d.applicability === "applicable" && d.score === null) nullScore[d.id] = (nullScore[d.id] ?? 0) + 1;
    }
    recommendations += result.recommendations.items.length;
    nullSolutions += result.solutions.filter((s) => s.solution === null).length;
    // Frequency of the BLOCKING R6-C/R6-D patterns found by the explicit suite (observed here, asserted there).
    const state = (id: string) => result.scoring.dimensions.flatMap((d) => d.evidence).find((e) => e.questionId === id)?.state;
    if (state("q2_process_systemization") === "weak" && solutionIds(result).some((s) => s === "operational_automation" || s === "follow_up_automation")) automationOnInformal += 1;
    result.recommendations.items.forEach((rec, i) => {
      if (!result.solutions[i]!.solution) return;
      const negative = rec.sourceQuestionIds.filter((id) => ["missing", "weak", "partial"].includes(state(id) ?? ""));
      if (negative.length > 0 && negative.every((id) => ["q2_operations_handoffs", "q2_b2b_status_visibility"].includes(id))) supportingOnlySolutions += 1;
    });
  }
  const stats = {
    seed: FUZZ_SEED, routedRuns: runs.length, interpretedRuns: INTERPRETED_RUNS, families, terminalReasons: terminal,
    routeLength: { min: lengths[0], median: lengths[Math.floor(lengths.length / 2)], max: lengths.at(-1) },
    hardCapHits: runs.filter((r) => r.hardCap).length, budgetBlocked: terminal.budget_blocked ?? 0,
    unknownRate: Number((unknown / answers).toFixed(3)), naRate: Number((na / answers).toFixed(3)),
    applicableByDimension: applicable, nullScoreWhenApplicable: nullScore, licenseDistribution: license,
    solutionNullFrequency: Number((nullSolutions / Math.max(1, recommendations)).toFixed(3)),
    blockingPatternObservations: { automationOnInformalProcess: automationOnInformal, solutionFromSupportingOnlyNegative: supportingOnlySolutions },
    timings,
  };
  // `budget_blocked` is an honest R5-certified terminal (useful work left unselected by a module/base
  // budget, `ready=false`), never a silent stop: every blocked route must carry exactly that explanation.
  const blocked = runs.filter((r) => r.terminalReason === "budget_blocked").map((r) => {
    const useful = r.plan.evidenceSufficiency.usefulQuestionIds;
    const skips = useful.map((id) => `${id}:${r.plan.trace.find((t) => t.questionId === id)?.skipReason}`);
    return { index: r.index, family: r.family, ready: r.plan.completion.ready, skips };
  });
  console.log(`R7B_FUZZ_STATS ${JSON.stringify({ ...stats, budgetBlockedRoutes: blocked })}`);
  assert.equal(stats.hardCapHits, 0);
  for (const b of blocked) {
    assert.equal(b.ready, false, `#${b.index}: budget_blocked must not report ready`);
    assert.ok(b.skips.length > 0 && b.skips.every((s) => s.endsWith(":module_budget") || s.endsWith(":base_budget")), `#${b.index}: budget_blocked without a module/base budget explanation: ${b.skips}`);
  }
});
